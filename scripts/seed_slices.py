def _dark_reaction() -> dict[str, Any]:
    rng = random.Random(SEED + 1)
    metadata = _metadata(
        title="Synthetic failed hydrothermal ZnO crystallization",
        material="zinc oxide",
        reaction="hydrothermal crystallization",
        owner="lab_synthesis",
        classification="dark_matter_failure",
        summary="Unsuccessful target-phase crystallization retained as usable negative evidence.",
        model="Simulated hydrothermal time-course with low target crystallinity and final low yield.",
    )
    metadata["temperature_c"] = 120.0
    metadata["outcome"] = "failed"
    metadata["failure_reason"] = "Predominantly amorphous precipitate; target-phase crystallinity below 5%."
    metadata["testing_conditions"] = {
        "solvent": "water",
        "initial_ph": 6.5,
        "duration_h": 12.0,
        "target_phase": "wurtzite ZnO",
        "outcome": "failed_crystallization",
        "measurement_method": "simulated XRD target-phase fraction",
    }
    metadata["extracted_metrics"] = {
        "target_phase_fraction_pct": 2.5,
        "crystallinity_fraction": 0.025,
        "isolated_yield_pct": 3.1,
        "outcome": "failed_crystallization",
    }
    metadata["notes"] = (
        "Predominantly amorphous precipitate; no confirmed target-phase crystallization. "
        "A synthetic failure record illustrates retention of negative results; "
        "it does not establish a universal publication-bias percentage."
    )
    rows: list[list[float | str]] = []
    for index in range(25):
        hour = index * 0.5
        temperature = 25 + 95 * min(hour / 1.0, 1.0)
        turbidity = 2.0 + 42 * (1 - math.exp(-hour / 3.0)) + rng.uniform(-0.15, 0.15)
        fraction = 2.5 * (hour / 12.0) ** 0.75
        rows.append([hour, temperature, round(turbidity, 4), round(fraction, 5), "amorphous precipitate"])
    return {
        "slice_id": "slice_dark_reaction",
        "domain": "hydrothermal_synthesis",
        "metadata": metadata,
        "columns": ["time_h", "temperature_c", "turbidity_ntu", "target_phase_fraction_pct", "observation"],
        "rows": rows,
    }


def _write_csv(path: Path, table: dict[str, Any]) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(table["columns"])
        writer.writerows(table["rows"])


def generate_slices(output_dir: Path = DEFAULT_OUTPUT_DIR) -> list[Path]:
    """Write five JSON/CSV datasets and the battery intra-cycle companion CSV.

    Existing files with the five benchmark names are deterministically replaced;
    unrelated files in the destination are left intact. Return the JSON paths.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    oer = _oer_valid()
    documents = [oer, _oer_violation(oer), _battery_valid(), _cwc_poison(), _dark_reaction()]
    json_paths: list[Path] = []
    for document in documents:
        path = output_dir / f"{document['slice_id']}.json"
        path.write_text(json.dumps(document, indent=2, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")
        _write_csv(path.with_suffix(".csv"), document)
        if "charge_curve" in document:
            _write_csv(output_dir / f"{document['slice_id']}_charge.csv", document["charge_curve"])
        json_paths.append(path)
    return json_paths


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    arguments = parser.parse_args()
    paths = generate_slices(arguments.output_dir)
    print(f"Generated {len(paths)} synthetic scientific datasets in {arguments.output_dir.resolve()}")
    for path in paths:
        print(path.name)


if __name__ == "__main__":
    main()
